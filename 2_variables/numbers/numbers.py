# integers
print(2 + 3) # 5
print(2 - 3) # -1
print(2 * 3) # 6
print(2 / 3) # 0.6666666666666666
print(2 ** 3) # 8
print(2 % 3) # 2
print(2 + 3 * 4) # 14
print((2 + 3) * 4) # 20

# floats
print(0.1 + 0.1) # 0.2
print(0.2 + 0.2) # 0.4
print(2 * 0.1) # 0.2
print(2 * 0.2) # 0.4
print(0.2 + 0.1) # 0.30000000000000004
print(3 * 0.1) # 0.30000000000000004

# integers and floats
